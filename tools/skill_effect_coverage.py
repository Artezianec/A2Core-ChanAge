#!/usr/bin/env python3
"""Skill effect engine coverage: client effect types and rows the server handles, before (legacy) and after the engine.

Reads the type registry from server/Aion.World/SkillEffectRegistry.cs (the entries between the skill-effect-types /
abnormal-effect-types markers), the client type counts and passives from tools/data/skill-effect-engine.json, and the
abnormal rows from boxes.json, skill-areas.json, ported-skill-abnormals.json and the engine file.
Writes tools/reports/skill-effect-coverage.md (or the path given). --check exits 1 when the report is stale.
See docs/SKILL-EFFECT-ENGINE.md.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from abnormal_coverage import class_of  # noqa: E402

REGISTRY = ROOT / 'server/Aion.World/SkillEffectRegistry.cs'
ENGINE = ROOT / 'tools/data/skill-effect-engine.json'
BOXES = ROOT / 'tools/data/boxes.json'
AREAS = ROOT / 'tools/data/skill-areas.json'
PORTED = ROOT / 'tools/data/ported-skill-abnormals.json'
CLASS_SKILLS = ROOT / 'tools/data/class-skills.json'
LEGACY_TRIGGERS = ROOT / 'tools/data/passive-triggers.json'
OUT = ROOT / 'tools/reports/skill-effect-coverage.md'

ENTRY = re.compile(r'new\("([^"]+)", Handler\.(\w+), (true|false)\)')
TRIGGER_TYPES = {
    'TriggerSkillByAttackAll', 'TriggerSkillByGetDamage', 'TriggerSkillByKill', 'TriggerSkillByGetAbnormal', 'TriggerSkillByAddAbnormal',
    'TriggerSkillBySelfBlock', 'TriggerSkillBySelfEvade', 'TriggerSkillBySelfWeaponBlock', 'TriggerSkillBySelfShieldBlock',
}
# Wired in the engine, but no server event raises them yet (the player's block / evade / parry rolls are not modelled).
DORMANT = {'TriggerSkillBySelfBlock', 'TriggerSkillBySelfEvade', 'TriggerSkillBySelfWeaponBlock', 'TriggerSkillBySelfShieldBlock',
           'TriggerSkillByAddAbnormal'}


def registry() -> tuple[dict, dict]:
    text = REGISTRY.read_text(encoding='utf-8')
    out = []
    for marker in ('skill-effect-types', 'abnormal-effect-types'):
        block = text.split(f'// {marker}:begin', 1)[1].split(f'// {marker}:end', 1)[0]
        out.append({m.group(1).lower(): (m.group(1), m.group(2), m.group(3) == 'true') for m in ENTRY.finditer(block)})
    return out[0], out[1]


def abnormal_rows() -> dict[int, list[str]]:
    """Effect types per abnormal, first table wins (AbnormalSpecs.Info order)."""
    rows: dict[int, list[str]] = {}
    boxes = json.loads(BOXES.read_text(encoding='utf-8')).get('abnormals', {})
    areas = json.loads(AREAS.read_text(encoding='utf-8')).get('abnormal_effects', {})
    ported = json.loads(PORTED.read_text(encoding='utf-8')).get('abnormals', {})
    engine = json.loads(ENGINE.read_text(encoding='utf-8')).get('abnormal_effects', {})
    for table, key in ((boxes, 'effects'), (areas, 'effects'), (ported, 'e'), (engine, 'effects')):
        for aid, row in table.items():
            if int(aid) in rows:
                continue
            effects = row.get(key) if isinstance(row, dict) else row
            rows[int(aid)] = [e[1] for e in effects or [] if isinstance(e, list) and len(e) > 1]
    return rows


def pct(n: int, d: int) -> str:
    return f'{n * 100 / d:.1f}%' if d else '-'


def build() -> str:
    skill_reg, abn_reg = registry()
    engine = json.loads(ENGINE.read_text(encoding='utf-8'))
    skill_counts: dict[str, int] = engine['skill_effect_types']
    abn_counts: dict[str, int] = engine['abnormal_effect_types']

    def cover(counts, reg):
        total_rows = sum(counts.values())
        before = {t: n for t, n in counts.items() if reg.get(t.lower(), (None, None, False))[2]}
        after = {t: n for t, n in counts.items() if t.lower() in reg}
        return total_rows, before, after

    s_rows, s_before, s_after = cover(skill_counts, skill_reg)
    a_rows, a_before, a_after = cover(abn_counts, abn_reg)

    lines = [
        '# Skill effect engine coverage',
        '',
        'GENERATED by `python tools/skill_effect_coverage.py` from `server/Aion.World/SkillEffectRegistry.cs` and',
        '`tools/data/skill-effect-engine.json` (client export 2026-11-22). See docs/SKILL-EFFECT-ENGINE.md.',
        '',
        '"Before" counts the types the server resolved before the engine (registry `legacy: true`); "after" every registered type.',
        '',
        '| Table | Types in client | Before: types | Before: rows | After: types | After: rows |',
        '|---|---|---|---|---|---|',
        f'| SkillEffect | {len(skill_counts)} | {len(s_before)} | {sum(s_before.values())} / {s_rows} ({pct(sum(s_before.values()), s_rows)}) '
        f'| {len(s_after)} | {sum(s_after.values())} / {s_rows} ({pct(sum(s_after.values()), s_rows)}) |',
        f'| SkillAbnormalEffect | {len(abn_counts)} | {len(a_before)} | {sum(a_before.values())} / {a_rows} ({pct(sum(a_before.values()), a_rows)}) '
        f'| {len(a_after)} | {sum(a_after.values())} / {a_rows} ({pct(sum(a_after.values()), a_rows)}) |',
        '',
    ]

    # ---- passives ----
    rows = abnormal_rows()
    class_skills = json.loads(CLASS_SKILLS.read_text(encoding='utf-8'))['skills']
    legacy = set(json.loads(LEGACY_TRIGGERS.read_text(encoding='utf-8')).get('triggers', {}))
    per_class = defaultdict(Counter)
    unhandled_passive_types = Counter()
    for sid, ids in engine['passives'].items():
        types = [t for a in ids for t in rows.get(a, []) if t not in ('None', 'NoEffect')]
        if not types:
            state_before = state_after = 'no rows'
        else:
            known_after = [t.lower() in abn_reg and t not in DORMANT for t in types]
            # passive-triggers.json fired the attack / damaged procs (Abnormal_True only); block / evade rows went to OnHit (wrong event).
            known_before = [abn_reg.get(t.lower(), (None, None, False))[2] or (t in TRIGGER_TYPES and t not in DORMANT and sid in legacy) for t in types]
            state_after = 'full' if all(known_after) else 'partial' if any(known_after) else 'none'
            state_before = 'full' if all(known_before) else 'partial' if any(known_before) else 'none'
            for t, ok in zip(types, known_after):
                if not ok:
                    unhandled_passive_types[t] += 1
        cls = class_of(int(sid)) or 'Other'
        per_class[cls][f'before {state_before}'] += 1
        per_class[cls][f'after {state_after}'] += 1
        per_class[cls]['total'] += 1
    lines += [
        '## Class passives (client Abnormal_Passive rows)',
        '',
        '"full": every effect row of the passive\'s abnormals has a handler; "partial": some do. Before, only the stat rows and',
        'the Abnormal_True procs of passive-triggers.json worked (MP / HP heal procs, chances and cooldowns were dropped).',
        '',
        '| Class | Passives | Before full | Before partial | After full | After partial | No rows |',
        '|---|---|---|---|---|---|---|',
    ]
    totals = Counter()
    for cls in sorted(per_class):
        c = per_class[cls]
        totals.update(c)
        lines.append(f"| {cls} | {c['total']} | {c['before full']} | {c['before partial']} | {c['after full']} | {c['after partial']} | {c['after no rows']} |")
    lines.append(f"| **All** | {totals['total']} | {totals['before full']} | {totals['before partial']} | {totals['after full']} | "
                 f"{totals['after partial']} | {totals['after no rows']} |")
    lines.append('')
    if unhandled_passive_types:
        lines += ['Passive effect types still without a handler (rows):', '']
        lines += [f'- `{t}`: {n}' for t, n in unhandled_passive_types.most_common()]
        lines.append('')

    # ---- engine data ----
    triggers = [s for specs in engine['triggers'].values() for s in specs]
    on = Counter(s['on'] for s in triggers if not s.get('variant'))
    proc_types = Counter(r['type'] for p in engine['proc_skills'].values() for r in p['rows'])
    unhandled_proc = {t: n for t, n in proc_types.items() if t not in
                      {'HpHeal', 'HpHealRatio', 'MpHeal', 'MpHealRatio', 'SpHeal', 'SpHealRatio', 'APHeal', 'APHealRatio',
                       'Abnormal_True', 'Abnormal', 'Abnormal_Cc', 'Dispel_True', 'Dispel_Cc', 'Dispel', 'DecreaseCooltime', 'Damage'}}
    lines += [
        '## Engine data',
        '',
        f"- Trigger abnormals: {len(engine['triggers'])} ({sum(on.values())} base rows, "
        f"{sum(1 for s in triggers if s.get('variant'))} upgrade-tier variants not fired): "
        + ', '.join(f'{k} {v}' for k, v in on.most_common()),
        f"- Dormant trigger kinds (no server event yet): {', '.join(sorted(DORMANT))}",
        f"- Proc skills: {len(engine['proc_skills'])}; rows by type: " + ', '.join(f'{k} {v}' for k, v in proc_types.most_common()),
        f"- Proc row types the engine skips (logged once): " + (', '.join(f'{k} {v}' for k, v in sorted(unhandled_proc.items())) or 'none'),
        f"- Skills with life steal (Damage drain columns): {len(engine['drains'])}",
        f"- NPC skills with HP-ratio damage: {len(engine['ratio_damage'])}",
        f"- NPC skills with abnormal rows the ported table lacked: {len(engine['npc_abnormals'])}",
        f"- Abnormals whose rows only the engine carries: {len(engine['abnormal_effects'])}",
        '',
        '## Types without a handler',
        '',
        '| Table | Type | Client rows |',
        '|---|---|---|',
    ]
    for table, counts, after in (('SkillEffect', skill_counts, s_after), ('SkillAbnormalEffect', abn_counts, a_after)):
        for t, n in sorted(counts.items(), key=lambda kv: -kv[1]):
            if t not in after:
                lines.append(f'| {table} | `{t}` | {n} |')
    lines.append('')
    return '\n'.join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('out', nargs='?', default=str(OUT))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    text = build()
    out = Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding='utf-8') != text:
            print(f'{out} is stale: run python tools/skill_effect_coverage.py', file=sys.stderr)
            return 1
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    print(out.relative_to(ROOT))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
