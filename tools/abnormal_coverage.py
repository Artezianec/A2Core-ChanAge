#!/usr/bin/env python3
"""Coverage report for class passive abnormals: exported / improvised / missing per class.

Reads tools/data/class-skills.json, boxes.json passives, and skill-areas.json abnormal_effects.
Writes tools/reports/abnormal-coverage.md by default.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLASS_SKILLS = ROOT / "tools/data/class-skills.json"
BOXES = ROOT / "tools/data/boxes.json"
SKILL_AREAS = ROOT / "tools/data/skill-areas.json"
OUT = ROOT / "tools/reports/abnormal-coverage.md"

CLASSES = ("Gladiator", "Templar", "Ranger", "Assassin", "Sorcerer", "Spiritmaster", "Cleric", "Chanter")


def class_of(skill_id: int) -> str | None:
    fam = skill_id // 1_000_000
    bases = {"Gladiator": 11, "Templar": 12, "Ranger": 14, "Assassin": 13, "Sorcerer": 15,
             "Spiritmaster": 16, "Cleric": 17, "Chanter": 18}
    for name, digit in bases.items():
        if fam == digit:
            return name
    if 1000 <= skill_id < 2000:
        return "Common"
    return None


def main() -> int:
    out_path = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    skills = json.loads(CLASS_SKILLS.read_text(encoding="utf-8"))["skills"]
    boxes = json.loads(BOXES.read_text(encoding="utf-8"))
    passives_map = boxes.get("passives", {})
    areas = json.loads(SKILL_AREAS.read_text(encoding="utf-8"))
    abnormal_effects = areas.get("abnormal_effects", {})
    boxes_abn = set(boxes.get("abnormals", {}))

    by_class: dict[str, dict[str, list]] = defaultdict(lambda: {"exported": [], "improvised": [], "missing": []})

    for skill_id_str, row in skills.items():
        if row.get("type") != "Passive":
            continue
        skill_id = int(skill_id_str)
        cls = class_of(skill_id) or "Unknown"
        for abn in passives_map.get(skill_id_str, []):
            key = str(abn)
            if key in abnormal_effects:
                src = abnormal_effects[key].get("source", "client")
                bucket = "improvised" if src == "override" else "exported"
                by_class[cls][bucket].append((skill_id, abn, row.get("name", skill_id_str)))
            elif key in boxes_abn:
                by_class[cls]["exported"].append((skill_id, abn, row.get("name", skill_id_str) + " (boxes)"))
            else:
                by_class[cls]["missing"].append((skill_id, abn, row.get("name", skill_id_str)))

    totals = {"exported": 0, "improvised": 0, "missing": 0}
    for data in by_class.values():
        for bucket in totals:
            totals[bucket] += len(data[bucket])
    total = sum(totals.values()) or 1
    lines = [
        "# Abnormal passive coverage",
        "",
        "Per-class passive skills (128 total): whether their `Abnormal_Passive` ids have effect rows.",
        "",
        f"Summary: exported {totals['exported']}/{total} ({100 * totals['exported'] // total}%), "
        f"improvised {totals['improvised']}, missing {totals['missing']}.",
        "",
        "Generated by `python tools/abnormal_coverage.py` (after `python tools/client_skill_sync.py`).",
        "",
    ]
    for cls in [*CLASSES, "Common", "Unknown"]:
        if cls not in by_class:
            continue
        data = by_class[cls]
        lines.append(f"## {cls}")
        lines.append(f"- exported: {len(data['exported'])}")
        lines.append(f"- improvised: {len(data['improvised'])}")
        lines.append(f"- missing: {len(data['missing'])}")
        if data["missing"][:8]:
            lines.append("- missing examples: " + ", ".join(f"{n} ({a})" for _, a, n in data["missing"][:8]))
        lines.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(out_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())