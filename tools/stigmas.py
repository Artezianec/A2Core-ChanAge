"""Stigmas: each class's stigma skills and the stigma rules (tools/data/stigmas.json, docs/STIGMAS.md).

Ported from ckrealm/A2Core (branch friends-server, commits 8416c5a and dbc178b, AGPL-3.0) and rebuilt against the client
catalogue instead of the developer kit.

Recovered from the client (game-catalog-v2 entries.jsonl, each skill's SkillAcquireData rows under
relationships.acquisition): every row with AcquireType ESkillAcquireType::Stigma. That is 117 stigma skills, 13 per class
for the 8 classes and the Brawler (client class Fighter), levels 1-20, one cost ladder for all of them (CostStigmaPoint
1/1/1/1/1, 2 x5, 4 x5, 8 x5), every level at character level 22, level 1 also at AscensionGrade_3. Each skill's name,
cooldown, casting time, weapons, target and MP/HP/SP cost come from the same entry (Skill.dat facts).

OURS: the damage rows. Skill.dat damage (SkillEffect) rows for the stigma skills are not exported, so a stigma aimed at a
MainTarget borrows the damage of a comparable skill of its class (seed: the damage rows already in stigmas.json, first
generated by ckrealm's tools/stigmas.py from the class's damage skills in the same cooldown band). Self stigmas carry
self_buffs rows (caster Abnormal_True / Abnormal_Cc from SkillEffect.dat) for the ClassSelfBuffs path on cast.

CANDIDATE (params): shards per level, slot levels, the per-level power. See docs/STIGMAS.md.

Level variants (generated.variants, stigma -> [[from level, variant skill]]): from stigma level 5 the client casts a variant,
id + 10 at 5-9, + 20 at 10-14, + 30 at 15-19, + 40 at 20 (OBSERVED in the community recordings of 2026-11-05/06, ported from
Addiboii/A2Core 771ed0d). The variants and their chain steps carry Skill.dat cast rows taken from that upstream stigmas.json
(build 26262663); `build` keeps them, it only rewrites the 117 stigmas themselves.

    python tools/stigmas.py build --catalog research/local/game-catalog-v2/entries.jsonl
    python tools/stigmas.py patch-self-buffs
    python tools/stigmas.py check --catalog research/local/game-catalog-v2/entries.jsonl
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'tools/data/stigmas.json'
DEFAULT_CATALOG = ROOT / 'research/local/game-catalog-v2/entries.jsonl'
STIGMA = 'ESkillAcquireType::Stigma'
OVERRIDES = ROOT / 'tools/data/stigma-self-buff-overrides.json'
SKILL_AREAS = ROOT / 'tools/data/skill-areas.json'

sys.path.insert(0, str(Path(__file__).resolve().parent))
from data_json import write_data_json
import skill_areas as sa


def _enum(value):
    return value.split('::', 1)[1] if isinstance(value, str) and '::' in value else value


def read_catalog(path):
    """{class: {skill id: (entry, [acquire rows])}} for every Stigma SkillAcquireData row."""
    found = {}
    with open(path, encoding='utf-8') as handle:
        for line in handle:
            if '"ESkillAcquireType::Stigma"' not in line:
                continue
            entry = json.loads(line)
            if entry.get('kind') != 'skills':
                continue
            rows = [r for r in (entry.get('relationships') or {}).get('acquisition') or [] if r.get('AcquireType') == STIGMA]
            for row in rows:
                cls = _enum(row['ClassType'])
                found.setdefault(cls, {}).setdefault(entry['id'], (entry, []))[1].append(row)
    return found


def cost_ladder(found):
    """[(level, shards)] shared by every stigma, or raises when the skills disagree."""
    ladders = set()
    for skills in found.values():
        for _, rows in skills.values():
            ladders.add(tuple(sorted((r['SkillLevel'], r['CostStigmaPoint']) for r in rows)))
    if len(ladders) != 1:
        raise ValueError(f'stigma cost ladders differ: {len(ladders)}')
    return list(next(iter(ladders)))


def bands(ladder):
    out = []
    for level, shards in ladder:
        if out and out[-1]['shards'] == shards and out[-1]['to'] == level - 1:
            out[-1]['to'] = level
        else:
            out.append({'from': level, 'to': level, 'shards': shards})
    return out


def definition(entry, seed):
    facts = entry.get('facts') or {}
    target = _enum(facts.get('TargetProcessType')) or 'MainTarget'
    weapons = [_enum(w) for w in facts.get('NeedMainWeaponTypes') or []]
    seed = seed or {}
    damage = (seed.get('damage') or []) if target == 'MainTarget' else []
    out = {
        'name': entry.get('name'),
        'type': _enum(facts.get('SkillType')) or 'Active',
        'target': target,
        'weapons': weapons,
        'cooldown_ms': int(facts.get('NeedCoolTime') or 0),
        'casting_ms': int(facts.get('CastingTime') or 0),
        'cost': {'mp': int(facts.get('NeedCostMp') or 0), 'hp': int(facts.get('NeedCostHp') or 0), 'sp': int(facts.get('NeedCostSp') or 0)},
        'damage': damage,
        'damage_source': 'OURS (comparable class skill)' if damage else 'none (effects not exported)',
    }
    if target == 'Self' and seed.get('self_buffs'):
        out['self_buffs'] = seed['self_buffs']
        if seed.get('self_buffs_source'):
            out['self_buffs_source'] = seed['self_buffs_source']
    return out


def _client_self_buff_tables():
    from client_export import load_rows
    skills = {sa._value(r['ID']): r for r in load_rows('Skill')}
    filters = {sa._value(r['ID']): r for r in load_rows('SkillEffectFilter')}
    debuff_groups = sa._debuff_groups('client:SkillEffect', sa.ABNORMAL_EFFECTS)
    return skills, filters, debuff_groups


def self_buff_rows(skill_id, skills, filters, debuff_groups):
    """PortedSkillAbnormals.Row shape: [abnormal, min_ms, max_ms, level, chance, effect_row]."""
    row = skills.get(skill_id)
    if not row:
        return []
    found = []
    seq = 0
    for timed in row.get('SkillEffectTimeDataList', []):
        seq += 1
        group = sa._value(timed.get('SkillEffectGroupId', 0))
        filter_id = sa._value(timed.get('SkillEffectFilterId', 0))
        side = sa._effect_filter_side(filters.get(filter_id))
        for debuff in debuff_groups.get(group, []):
            if side != 'caster':
                continue
            abnormal, min_ms, max_ms, _held = debuff
            found.append([abnormal, min_ms, max_ms, 1, 10000, seq])
    return found


def patch_self_buffs(data_path=DATA, overrides_path=OVERRIDES):
    """Fill self_buffs on every stigma skill (and variants) from client SkillEffect, plus stigma-only abnormal_effects."""
    current = json.loads(Path(data_path).read_text(encoding='utf-8'))
    overrides = json.loads(Path(overrides_path).read_text(encoding='utf-8')) if Path(overrides_path).is_file() else {}
    skills, filters, debuff_groups = _client_self_buff_tables()
    skill_areas_ab = {}
    if SKILL_AREAS.is_file():
        skill_areas_ab = json.loads(SKILL_AREAS.read_text(encoding='utf-8')).get('abnormal_effects') or {}

    generated = current.setdefault('generated', {})
    stigma_skills = generated.get('skills') or {}
    variants = generated.get('variants') or {}
    missing_self = []

    for skill_id, entry in list(stigma_skills.items()):
        if entry.get('target') != 'Self':
            entry.pop('self_buffs', None)
            entry.pop('self_buffs_source', None)
            continue
        sid = int(skill_id)
        rows = self_buff_rows(sid, skills, filters, debuff_groups)
        override = (overrides.get('skills') or {}).get(skill_id)
        if override:
            rows = override
        if rows:
            entry['self_buffs'] = rows
            entry['self_buffs_source'] = 'client SkillEffect (tools/stigmas.py)'
        else:
            entry.pop('self_buffs', None)
            entry.pop('self_buffs_source', None)
            missing_self.append(sid)

    for stigma, steps in variants.items():
        base = stigma_skills.get(stigma) or {}
        for step in steps:
            if len(step) < 2:
                continue
            variant_id = str(step[1])
            if variant_id not in stigma_skills:
                continue
            if stigma_skills[variant_id].get('target') != 'Self':
                continue
            vid = int(variant_id)
            rows = self_buff_rows(vid, skills, filters, debuff_groups) or base.get('self_buffs')
            override = (overrides.get('skills') or {}).get(variant_id)
            if override:
                rows = override
            if rows:
                stigma_skills[variant_id]['self_buffs'] = rows
                stigma_skills[variant_id]['self_buffs_source'] = base.get('self_buffs_source') or 'client SkillEffect (tools/stigmas.py)'

    used_abnormals = {row[0] for entry in stigma_skills.values() for row in entry.get('self_buffs') or []}
    exported = sa._abnormal_effects(sa.ABNORMAL_EFFECTS, wanted=used_abnormals)
    stigma_ab = {}
    for abnormal in sorted(used_abnormals):
        key = str(abnormal)
        if key in skill_areas_ab:
            continue
        if abnormal in exported:
            stigma_ab[key] = {'effects': exported[abnormal], 'source': 'client'}
    for abnormal, entry in (overrides.get('abnormals') or {}).items():
        key = str(abnormal)
        if key in skill_areas_ab:
            continue
        if stigma_ab.get(key, {}).get('source') == 'client' and entry.get('effects'):
            continue
        if entry.get('effects'):
            stigma_ab[key] = {'effects': [[int(abnormal), *row] for row in entry['effects']], 'source': 'override'}
    if stigma_ab:
        current['abnormal_effects'] = stigma_ab
    else:
        current.pop('abnormal_effects', None)

    bases = sorted({sid - sid % 10 if sid % 10 else sid for sid in missing_self if sid < 90_000_000})
    current['params']['self_buff_missing'] = bases
    current['params']['self_buff_missing_about'] = (
        'Self stigmas with no caster Abnormal_True/Cc row (Toggle, heals, summons): cast accepted, ClassSelfBuffs has nothing to apply.'
    )
    write_data_json(data_path, current)
    with_self = sum(1 for entry in stigma_skills.values() if entry.get('self_buffs'))
    return with_self, bases


def build(catalog, data_path=DATA):
    current = json.loads(Path(data_path).read_text(encoding='utf-8'))
    seed = current.get('generated', {}).get('skills', {})
    found = read_catalog(catalog)
    ladder = cost_ladder(found)
    current['params']['costs'] = bands(ladder)
    current['params']['max_skill_level'] = max(level for level, _ in ladder)
    need = {r['NeedCharacterLevel'] for skills in found.values() for _, rows in skills.values() for r in rows}
    current['params']['unlock_level'] = min(need)
    classes = {cls: sorted(skills) for cls, skills in sorted(found.items())}
    skills = {}
    for cls, by_id in sorted(found.items()):
        for skill_id, (entry, _) in sorted(by_id.items()):
            skills[str(skill_id)] = definition(entry, seed.get(str(skill_id)))
    # The level variants and their chain steps (not stigma rows themselves) are kept as they are.
    for skill_id, extra in seed.items():
        if skill_id not in skills:
            skills[skill_id] = extra
    current['generated']['classes'] = classes
    current['generated']['skills'] = skills
    Path(data_path).write_text(json.dumps(current, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    patch_self_buffs(data_path)
    return json.loads(Path(data_path).read_text(encoding='utf-8'))


def check(catalog, data_path=DATA):
    """Problems between stigmas.json and the catalogue (empty when they agree)."""
    data = json.loads(Path(data_path).read_text(encoding='utf-8'))
    found = read_catalog(catalog)
    problems = []
    classes = data['generated']['classes']
    for cls, by_id in found.items():
        if sorted(by_id) != sorted(classes.get(cls, [])):
            problems.append(f'{cls}: stigma list differs')
    if bands(cost_ladder(found)) != data['params']['costs']:
        problems.append('cost ladder differs')
    for cls, by_id in found.items():
        for skill_id, (entry, _) in by_id.items():
            have = data['generated']['skills'].get(str(skill_id))
            want = definition(entry, have)
            if have is None or any(have.get(k) != want[k] for k in ('name', 'cooldown_ms', 'casting_ms', 'cost', 'weapons', 'target')):
                problems.append(f'{skill_id}: definition differs from Skill.dat facts')
    missing = data['params'].get('self_buff_missing') or []
    for skill_id, entry in data['generated']['skills'].items():
        if entry.get('target') == 'Self' and int(skill_id) not in missing and not entry.get('self_buffs'):
            problems.append(f'{skill_id}: self stigma without self_buffs')
    return problems


def check_self_buffs(data_path=DATA):
    data = json.loads(Path(data_path).read_text(encoding='utf-8'))
    skills = data['generated']['skills']
    missing = set(data['params'].get('self_buff_missing') or [])
    problems = []
    for skill_id, entry in skills.items():
        if entry.get('target') != 'Self':
            continue
        sid = int(skill_id)
        if sid in missing:
            continue
        if not entry.get('self_buffs'):
            problems.append(f'{skill_id}: expected self_buffs')
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('command', choices=('build', 'check', 'patch-self-buffs', 'check-self-buffs'))
    parser.add_argument('--catalog', type=Path, default=DEFAULT_CATALOG)
    args = parser.parse_args(argv)
    if args.command == 'build':
        data = build(args.catalog)
        print(f"{sum(len(v) for v in data['generated']['classes'].values())} stigma skills written to {DATA.relative_to(ROOT)}")
        return 0
    if args.command == 'patch-self-buffs':
        with_self, missing = patch_self_buffs()
        print(f'{DATA.relative_to(ROOT)}: {with_self} skills with self_buffs, {len(missing)} base self stigmas still without Abnormal rows')
        return 0
    if args.command == 'check-self-buffs':
        problems = check_self_buffs()
        for p in problems:
            print(p)
        return 1 if problems else 0
    problems = check(args.catalog)
    for p in problems:
        print(p)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())