"""Stigmas: each class's stigma skills and the stigma rules (tools/data/stigmas.json, docs/STIGMAS.md).

Ported from ckrealm/A2Core (branch friends-server, commits 8416c5a and dbc178b, AGPL-3.0) and rebuilt against the client
catalogue instead of the developer kit.

Recovered from the client (game-catalog-v2 entries.jsonl, each skill's SkillAcquireData rows under
relationships.acquisition): every row with AcquireType ESkillAcquireType::Stigma. That is 117 stigma skills, 13 per class
for the 8 classes and the Brawler (client class Fighter), levels 1-20, one cost ladder for all of them (CostStigmaPoint
1/1/1/1/1, 2 x5, 4 x5, 8 x5), every level at character level 22, level 1 also at AscensionGrade_3. Each skill's name,
cooldown, casting time, weapons, target and MP/HP/SP cost come from the same entry (Skill.dat facts).

OURS: the damage rows. Skill.dat damage (SkillEffect) rows for the stigma skills are not exported, so a stigma aimed at a
MainTarget borrows the damage of a comparable skill of its class (seed: the damage rows already in stigmas.json, first
generated by ckrealm's tools/stigmas.py from the class's damage skills in the same cooldown band). Self/area stigmas get
no damage rows: they cast, but do nothing until their effects are exported.

CANDIDATE (params): shards per level, slot levels, the per-level power. See docs/STIGMAS.md.

    python tools/stigmas.py build --catalog research/local/game-catalog-v2/entries.jsonl
    python tools/stigmas.py check --catalog research/local/game-catalog-v2/entries.jsonl
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'tools/data/stigmas.json'
DEFAULT_CATALOG = ROOT / 'research/local/game-catalog-v2/entries.jsonl'
STIGMA = 'ESkillAcquireType::Stigma'


def _enum(value):
    return value.split('::', 1)[1] if isinstance(value, str) and '::' in value else value


def read_catalog(path):
    """{class: {skill id: (entry, [acquire rows])}} for every Stigma SkillAcquireData row."""
    found = {}
    with open(path, encoding='utf-8') as handle:
        for line in handle:
            if '"ESkillAcquireType::Stigma"' not in line:
                continue
            entry = json.loads(line)
            if entry.get('kind') != 'skills':
                continue
            rows = [r for r in (entry.get('relationships') or {}).get('acquisition') or [] if r.get('AcquireType') == STIGMA]
            for row in rows:
                cls = _enum(row['ClassType'])
                found.setdefault(cls, {}).setdefault(entry['id'], (entry, []))[1].append(row)
    return found


def cost_ladder(found):
    """[(level, shards)] shared by every stigma, or raises when the skills disagree."""
    ladders = set()
    for skills in found.values():
        for _, rows in skills.values():
            ladders.add(tuple(sorted((r['SkillLevel'], r['CostStigmaPoint']) for r in rows)))
    if len(ladders) != 1:
        raise ValueError(f'stigma cost ladders differ: {len(ladders)}')
    return list(next(iter(ladders)))


def bands(ladder):
    out = []
    for level, shards in ladder:
        if out and out[-1]['shards'] == shards and out[-1]['to'] == level - 1:
            out[-1]['to'] = level
        else:
            out.append({'from': level, 'to': level, 'shards': shards})
    return out


def definition(entry, seed):
    facts = entry.get('facts') or {}
    target = _enum(facts.get('TargetProcessType')) or 'MainTarget'
    weapons = [_enum(w) for w in facts.get('NeedMainWeaponTypes') or []]
    damage = (seed or {}).get('damage') or [] if target == 'MainTarget' else []
    return {
        'name': entry.get('name'),
        'type': _enum(facts.get('SkillType')) or 'Active',
        'target': target,
        'weapons': weapons,
        'cooldown_ms': int(facts.get('NeedCoolTime') or 0),
        'casting_ms': int(facts.get('CastingTime') or 0),
        'cost': {'mp': int(facts.get('NeedCostMp') or 0), 'hp': int(facts.get('NeedCostHp') or 0), 'sp': int(facts.get('NeedCostSp') or 0)},
        'damage': damage,
        'damage_source': 'OURS (comparable class skill)' if damage else 'none (effects not exported)',
    }


def build(catalog, data_path=DATA):
    current = json.loads(Path(data_path).read_text(encoding='utf-8'))
    seed = current.get('generated', {}).get('skills', {})
    found = read_catalog(catalog)
    ladder = cost_ladder(found)
    current['params']['costs'] = bands(ladder)
    current['params']['max_skill_level'] = max(level for level, _ in ladder)
    need = {r['NeedCharacterLevel'] for skills in found.values() for _, rows in skills.values() for r in rows}
    current['params']['unlock_level'] = min(need)
    classes = {cls: sorted(skills) for cls, skills in sorted(found.items())}
    skills = {}
    for cls, by_id in sorted(found.items()):
        for skill_id, (entry, _) in sorted(by_id.items()):
            skills[str(skill_id)] = definition(entry, seed.get(str(skill_id)))
    current['generated']['classes'] = classes
    current['generated']['skills'] = skills
    Path(data_path).write_text(json.dumps(current, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    return current


def check(catalog, data_path=DATA):
    """Problems between stigmas.json and the catalogue (empty when they agree)."""
    data = json.loads(Path(data_path).read_text(encoding='utf-8'))
    found = read_catalog(catalog)
    problems = []
    classes = data['generated']['classes']
    for cls, by_id in found.items():
        if sorted(by_id) != sorted(classes.get(cls, [])):
            problems.append(f'{cls}: stigma list differs')
    if bands(cost_ladder(found)) != data['params']['costs']:
        problems.append('cost ladder differs')
    for cls, by_id in found.items():
        for skill_id, (entry, _) in by_id.items():
            have = data['generated']['skills'].get(str(skill_id))
            want = definition(entry, have)
            if have is None or any(have.get(k) != want[k] for k in ('name', 'cooldown_ms', 'casting_ms', 'cost', 'weapons', 'target')):
                problems.append(f'{skill_id}: definition differs from Skill.dat facts')
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('command', choices=('build', 'check'))
    parser.add_argument('--catalog', type=Path, default=DEFAULT_CATALOG)
    args = parser.parse_args(argv)
    if args.command == 'build':
        data = build(args.catalog)
        print(f"{sum(len(v) for v in data['generated']['classes'].values())} stigma skills written to {DATA.relative_to(ROOT)}")
        return 0
    problems = check(args.catalog)
    for p in problems:
        print(p)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
