using System.Globalization;
using System.Text;

namespace Aion.World;

/// <summary>
/// Data-driven audit of every learnable class skill (and specialization children) at progression cap. Theory checks only:
/// definitions, side-table lookup parity, damage / heal / abnormal resolution, wire effect ids, projectiles / zones, SkillCond producers.
/// </summary>
public static class LearnableSkillAudit
{
    public enum Status { Ok, Fail, Candidate, Skip }

    public sealed record Row(string Class, int SkillId, string Name, Status Status, string Reason);

    internal static readonly string[] PlayableClasses =
        ["Gladiator", "Templar", "Assassin", "Ranger", "Sorcerer", "Elementalist", "Cleric", "Chanter"];

    static readonly HashSet<int> DevSkills = [11_999_001, 11_999_002, 11_999_003];

    static readonly HashSet<int> UtilitySkills =
    [
        16_009_999, 16_290_000, 16_290_001, 16_290_002, 16_290_003, 16_290_004,
    ];

    static readonly Dictionary<int, string> FamilyClass = new()
    {
        [11] = "Gladiator", [12] = "Templar", [13] = "Assassin", [14] = "Ranger",
        [15] = "Sorcerer", [16] = "Elementalist", [17] = "Cleric", [18] = "Chanter",
    };

    public static IReadOnlyList<Row> Run(GameData data, int? level = null)
    {
        var cap = level ?? data.MaxLevel;
        var producers = BuildCondProducers(data, cap);
        var effectIds = KnownEffectIds(data);
        var rows = new List<Row>();
        foreach (var className in PlayableClasses)
        {
            foreach (var skillId in SkillsToAudit(data, className, cap).Where(id => InClassKit(id, className)))
            {
                var row = AuditSkill(data, className, skillId, producers, effectIds);
                if (row is not null) rows.Add(row);
            }
        }
        return rows;
    }

    public static string FormatMarkdown(IReadOnlyList<Row> rows, GameData data, int level)
    {
        var byClass = rows.GroupBy(r => r.Class).OrderBy(g => g.Key, StringComparer.Ordinal);
        var counts = rows.GroupBy(r => r.Status).ToDictionary(g => g.Key, g => g.Count());
        var sb = new StringBuilder();
        sb.AppendLine("# Learnable skills audit");
        sb.AppendLine();
        sb.AppendLine($"Progression level **{level}** (embedded `class-skills.json` + `specialized-skills.json`). ");
        sb.AppendLine("Generated by `LearnableSkillAudit` (C# theory test, no playthrough). ");
        sb.AppendLine("Re-run: `dotnet test tests/Aion.World.Tests --filter LearnableSkillAuditTests.Write_report`.");
        sb.AppendLine();
        sb.AppendLine("## Summary");
        sb.AppendLine();
        sb.AppendLine("| Status | Count |");
        sb.AppendLine("| --- | ---: |");
        foreach (var status in new[] { Status.Ok, Status.Fail, Status.Candidate, Status.Skip })
            sb.AppendLine(CultureInfo.InvariantCulture, $"| {status} | {counts.GetValueOrDefault(status)} |");
        sb.AppendLine();
        sb.AppendLine("### Per class (fail / candidate)");
        sb.AppendLine();
        sb.AppendLine("| Class | Fail | Candidate | Skip | Ok |");
        sb.AppendLine("| --- | ---: | ---: | ---: | ---: |");
        foreach (var cls in PlayableClasses)
        {
            var slice = rows.Where(r => r.Class == cls).ToList();
            sb.AppendLine(CultureInfo.InvariantCulture,
                $"| {cls} | {slice.Count(r => r.Status == Status.Fail)} | {slice.Count(r => r.Status == Status.Candidate)} | {slice.Count(r => r.Status == Status.Skip)} | {slice.Count(r => r.Status == Status.Ok)} |");
        }
        sb.AppendLine();
        foreach (var group in byClass)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"## {group.Key}");
            sb.AppendLine();
            sb.AppendLine("| Skill id | Name | Status | Reason |");
            sb.AppendLine("| ---: | --- | --- | --- |");
            foreach (var row in group.OrderBy(r => r.SkillId))
                sb.AppendLine(CultureInfo.InvariantCulture,
                    $"| {row.SkillId} | {Escape(row.Name)} | {row.Status} | {Escape(row.Reason)} |");
            sb.AppendLine();
        }
        return sb.ToString();
    }

    static string Escape(string s) => s.Replace('|', '/');

    static bool InClassKit(int skillId, string className)
    {
        if (FamilyClass.TryGetValue(skillId / 1_000_000, out var cls))
            return cls.Equals(className, StringComparison.OrdinalIgnoreCase);
        if (SpecializedSkillTables.Embedded.ParentOf(skillId) is { } parent)
            return InClassKit(parent, className);
        return false;
    }

    static IEnumerable<int> SkillsToAudit(GameData data, string className, int level)
    {
        var profile = data.ProfileForClass(1, 1, className)
            ?? throw new InvalidOperationException($"No starter profile for {className}");
        var kit = data.SkillListForClient(className, level, profile).Select(k => k.SkillId).ToHashSet();
        var ids = new SortedSet<int>(kit);
        foreach (var parent in kit.Where(SpecializedSkillTables.Embedded.HasParts))
            foreach (var child in SpecializedSkillTables.Embedded.ChildrenOf(parent))
                ids.Add(child);
        return ids;
    }

    static Row? AuditSkill(GameData data, string className, int skillId, CondProducers producers, HashSet<int> effectIds)
    {
        if (DevSkills.Contains(skillId)) return null;
        var def = data.Skill(skillId);
        var name = def?.Name ?? skillId.ToString(CultureInfo.InvariantCulture);
        if (def is null)
            return new Row(className, skillId, name, Status.Fail, "missing_definition");
        if (UtilitySkills.Contains(skillId))
            return new Row(className, skillId, name, Status.Skip, "utility_handled_by_session");
        if (def.Type is "Passive")
            return new Row(className, skillId, name, Status.Skip, "passive");
        if (def.Type is "System")
            return new Row(className, skillId, name, Status.Skip, "system");
        if (SkillCooldown.IsBasicAutoAttack(def))
            return new Row(className, skillId, name, Status.Skip, "basic_attack_chain");

        var failures = new List<string>();
        var candidates = new List<string>();

        if (def.Type == "Active" && def.Weapons is { Length: > 0 })
        {
            // Cast path needs a weapon type; data must list at least one.
        }
        else if (def.Type != "Active" && def.Type != "Toggle")
            candidates.Add($"unusual_type:{def.Type}");

        SideTableParity(skillId, failures);

        var resolved = data.Skill(skillId)!;
        var hasDamage = resolved.Damage is { Length: > 0 };
        var zone = PcZones.For(skillId);
        var trap = PcTraps.For(skillId);
        var area = SkillAreas.For(skillId);
        var selfRows = PortedSkillAbnormals.SelfRows(skillId);
        var targetRows = PortedSkillAbnormals.TargetRows(skillId);
        var heals = area?.EffectRows.Any(r => r.Length > 0 && r[0] is "HpHeal" or "HpHealRatio" or "MpHeal" or "MpHealRatio") == true;

        if (def.Type is "Active" or "Toggle" && def.Target is not "Self" and not "MainSelf")
        {
            var attackShaped = hasDamage || area is { Max: > 0 } or { Projectile: > 0 }
                || area?.TargetDebuffRows.Any() == true || zone is not null || trap is not null;
            if (!attackShaped && selfRows.Count == 0 && heals != true && PcSummons.For(skillId) is null)
                failures.Add("damage_unresolved");
        }

        if (hasDamage)
        {
            ProjectileRows(skillId, resolved, failures);
            foreach (var row in resolved.Damage)
            {
                var wired = SkillSideData.WireEffectId(row.EffectId, skillId);
                if (wired <= 0)
                    failures.Add("wire_effect_zero");
                else if (!effectIds.Contains(wired) && !effectIds.Contains(row.EffectId))
                    candidates.Add($"wire_effect_unverified:{wired}");
                if (SpecializedSkillTables.Embedded.ParentOf(skillId) is not null
                    && wired == row.EffectId && row.EffectId / 100 != skillId)
                    failures.Add("wire_effect_needs_child_id");
            }
        }

        if (def.SkillCond is { } cond)
            SkillCondCheck(def, cond, producers, candidates);

        if (failures.Count > 0)
            return new Row(className, skillId, name, Status.Fail, string.Join("; ", failures.Distinct()));
        if (candidates.Count > 0)
            return new Row(className, skillId, name, Status.Candidate, string.Join("; ", candidates.Distinct()));
        return new Row(className, skillId, name, Status.Ok, "ok");
    }

    static void SideTableParity(int skillId, List<string> failures)
    {
        if (SpecializedSkillTables.Embedded.ParentOf(skillId) is not { } parent) return;
        if (PortedSkillAbnormals.SelfRows(parent).Count > 0 && PortedSkillAbnormals.SelfRows(skillId).Count == 0)
            failures.Add("self_abnormal_lookup");
        if (PcZones.For(parent) is not null && PcZones.For(skillId) is null)
            failures.Add("pc_zone_lookup");
        var parentArea = SkillAreas.For(parent);
        if (parentArea is { Max: > 0 } && SkillAreas.For(skillId) is not { Max: > 0 })
            failures.Add("skill_area_lookup");
        if (parentArea is { Projectile: > 0 } && GameSession.CastArea(GameData.Embedded, skillId) is not { Projectile: > 0 })
            failures.Add("cast_area_projectile");
    }

    static void ProjectileRows(int skillId, SkillDefinition def, List<string> failures)
    {
        var area = GameSession.CastArea(GameData.Embedded, skillId);
        var needsProjectile = area is { Projectile: > 0 }
            || def.Damage.Any(r => r.Projectile > 0);
        if (!needsProjectile) return;
        if (def.Damage.Length == 0) return;
        var rowProjectile = def.Damage.Any(r => r.Projectile > 0);
        var areaProjectile = area is { Projectile: > 0 };
        if (!rowProjectile && !areaProjectile)
            failures.Add("projectile_unresolved");
    }

    static void SkillCondCheck(SkillDefinition def, SkillCondNeed cond, CondProducers producers, List<string> candidates)
    {
        if (!SkillCondRegistry.IsKnownType(cond.Type))
        {
            candidates.Add($"skill_cond_unknown:{cond.Type}");
            return;
        }
        if (cond.Type.Equals(SkillCondRegistry.HasAbnormalGroupId, StringComparison.OrdinalIgnoreCase)
            && cond.AbnormalGroup is { } group)
        {
            if (def.SkillCondSource == "DATA_MISSING")
                candidates.Add($"skill_cond_DATA_MISSING:{group}");
            else if (!producers.Groups.Contains(group))
                candidates.Add($"skill_cond_group:{group}");
        }
        else if (cond.Type.Equals(SkillCondRegistry.HasAbnormalEffectType, StringComparison.OrdinalIgnoreCase)
            && cond.AbnormalEffect is { Length: > 0 } effect)
        {
            if (effect.Equals("Stagger", StringComparison.OrdinalIgnoreCase)
                || effect.Equals("Groggy", StringComparison.OrdinalIgnoreCase))
                return;
            if (!producers.Effects.Contains(effect))
                candidates.Add($"skill_cond_effect:{effect}");
        }
    }

    sealed record CondProducers(HashSet<int> Groups, HashSet<string> Effects);

    static CondProducers BuildCondProducers(GameData data, int level)
    {
        var groups = new HashSet<int>();
        var effects = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var className in PlayableClasses)
        {
            foreach (var skillId in SkillsToAudit(data, className, level))
            {
                if (data.Skill(skillId) is not { } def) continue;
                if (def.StaggerGauge > 0)
                    effects.Add("Stagger");
                if (SkillAreas.For(skillId) is { } area)
                {
                    foreach (var (abnormal, _, _, _) in area.TargetDebuffRows.Concat(area.CasterDebuffRows))
                    {
                        groups.Add(abnormal);
                        groups.Add(AbnormalStackRules.GroupOf(abnormal));
                        foreach (var t in SkillAreas.Abnormal(abnormal)?.Effects.Select(e => e.Type) ?? [])
                            effects.Add(t);
                    }
                }
                foreach (var row in PortedSkillAbnormals.TargetRows(skillId).Concat(PortedSkillAbnormals.SelfRows(skillId)))
                {
                    groups.Add(row.Abnormal);
                    groups.Add(AbnormalStackRules.GroupOf(row.Abnormal));
                    if (PortedSkillAbnormals.GroupOf(row.Abnormal) is { } g) groups.Add(g);
                }
                if (def.SkillCondGrant is { } grant)
                {
                    groups.Add(grant.Abnormal);
                    groups.Add(AbnormalStackRules.GroupOf(grant.Abnormal));
                }
                foreach (var cond in SkillEffectConditions.ProducerAbnormals(skillId))
                {
                    groups.Add(cond);
                    groups.Add(AbnormalStackRules.GroupOf(cond));
                }
            }
        }
        return new CondProducers(groups, effects);
    }

    static HashSet<int> KnownEffectIds(GameData data)
    {
        var set = new HashSet<int>();
        void AddFrom(SkillDefinition def, int castId)
        {
            foreach (var row in def.Damage)
            {
                set.Add(row.EffectId);
                set.Add(SkillSideData.WireEffectId(row.EffectId, castId));
            }
        }
        foreach (var className in PlayableClasses)
        {
            foreach (var skillId in SkillsToAudit(data, className, data.MaxLevel))
            {
                if (data.Skill(skillId) is { } def)
                    AddFrom(def, skillId);
            }
        }
        return set;
    }
}